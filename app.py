import html, os, requests, streamlit as st
from datetime import date
from dotenv import load_dotenv
from services.document_service import format_docx, format_pdf, format_txt
load_dotenv()
st.set_page_config(page_title=os.getenv("APP_TITLE", "LegalEase"), page_icon="⚖️", layout="wide")
BACKEND_URL = os.getenv("BACKEND_URL", "http://127.0.0.1:8000").rstrip("/")
LOGO_PATH = os.path.join(os.path.dirname(__file__), "assets", "logo.svg")

def preview_html(text):
    safe = html.escape(text).replace("\n\n", "<br><br>").replace("\n", "<br>")
    return f'<div style="background:#111827;color:#f9fafb;border:1px solid #374151;border-radius:14px;padding:24px;min-height:420px;max-height:620px;overflow-y:auto;line-height:1.65;font-family:Georgia,serif;">{safe}</div>'

st.markdown("<style>.main-title{text-align:center;font-size:2.5rem;font-weight:800}.sub-title{text-align:center;color:#6b7280;margin-bottom:2rem}</style>", unsafe_allow_html=True)
_, center, _ = st.columns([1,2,1])
with center: st.image(LOGO_PATH, width=110)
st.markdown('<div class="main-title">LegalEase</div>', unsafe_allow_html=True)
st.markdown('<div class="sub-title">AI-Powered Legal Document Generator</div>', unsafe_allow_html=True)
st.info("LegalEase creates draft documents. Review generated text and jurisdiction-specific requirements with a qualified legal professional before use.")

with st.form("document_form"):
    c1, c2 = st.columns(2)
    with c1:
        document_type = st.text_input("Document Type", placeholder="Employment Contract, NDA, Lease Agreement")
        parties = st.text_area("Parties Involved", placeholder="Jane Doe (Employee), ABC Corp (Employer)", height=140)
    with c2:
        effective_date = st.date_input("Effective Date", value=date.today())
        terms = st.text_area("Terms & Conditions", placeholder="Payment within 30 days; Confidentiality; Termination with 15 days notice", height=140, help="Separate terms with semicolons (;).")
    generate = st.form_submit_button("Generate Document", type="primary", use_container_width=True)

if generate:
    if not all([document_type.strip(), parties.strip(), terms.strip()]):
        st.error("Please fill in Document Type, Parties, and Terms.")
    else:
        payload = {"document_type": document_type.strip(), "parties": parties.strip(), "terms": terms.strip(), "effective_date": effective_date.isoformat()}
        with st.spinner("Generating your draft document..."):
            try:
                response = requests.post(f"{BACKEND_URL}/generate", json=payload, timeout=120)
                response.raise_for_status(); data = response.json()
                st.session_state.update(document=data["document"], document_type=data["document_type"], mode=data["mode"], terms=terms)
            except requests.RequestException as exc:
                st.error("Could not connect to the FastAPI backend. Make sure it is running."); st.caption(str(exc))

if "document" in st.session_state:
    st.divider()
    if st.session_state.get("mode") == "demo": st.warning("Demo mode is active because GEMINI_API_KEY is not configured. The complete UI/export workflow is still testable.")
    else: st.success("Document generated by Gemini.")
    st.subheader("Document Preview"); st.markdown(preview_html(st.session_state["document"]), unsafe_allow_html=True)
    st.subheader("Edit Document")
    st.session_state["document"] = st.text_area("Edit the generated document before downloading", value=st.session_state["document"], height=500, key="editable_document")
    doc_type = st.session_state.get("document_type", "Legal Document"); term_text = st.session_state.get("terms", "")
    txt_data = format_txt(st.session_state["document"])
    docx_data = format_docx(st.session_state["document"], doc_type, terms=term_text, logo_path=LOGO_PATH)
    pdf_data = format_pdf(st.session_state["document"], doc_type, logo_path=LOGO_PATH)
    d1,d2,d3 = st.columns(3)
    with d1: st.download_button("Download TXT", txt_data, "legalease_document.txt", "text/plain", use_container_width=True)
    with d2: st.download_button("Download DOCX", docx_data, "legalease_document.docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document", use_container_width=True)
    with d3: st.download_button("Download PDF", pdf_data, "legalease_document.pdf", "application/pdf", use_container_width=True)
